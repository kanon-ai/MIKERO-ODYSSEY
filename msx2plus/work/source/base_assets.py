def make_graphics():
 p=bytearray(2048);cs=[]
 for ch,rows in FONT.items():
  for y,row in enumerate(rows):p[ord(ch)*8+y]=int(row,2)<<2
 for i,rows in enumerate(ART):
  assert len(rows)==16 and all(len(r)==16 for r in rows)
  for q in range(4):
   for yy in range(8):
    y=(q//2)*8+yy;x=(q%2)*8
    p[(128+i*4+q)*8+yy]=int(rows[y][x:x+8].replace('.','0').replace('#','1'),2)
 for theme in range(4):
  c=bytearray([0xf1]*2048)
  for i in range(len(ART)):
   for q in range(4):
    for yy in range(8):
     y=(q//2)*8+yy;color=COLORS[i][y]
     if i==1:
      color=([5,4,3],[7,4,5],[10,6,9],[13,4,7])[theme][0 if y%4==0 else 2 if y in (13,14) else 1]
     c[(128+i*4+q)*8+yy]=(color<<4)|1
  cs.append(c)
 return bytes(p+b''.join(cs)).ljust(16384,b'\xff')

def dungeon(seed):
 r=random.Random(0x1a270000+seed);m=bytearray([1]*4096)
 centers=[(5,5)]+[(r.randrange(12,54),r.randrange(5,54)) for _ in range(11)]+[(55,55)]
 for i,(x,y) in enumerate(centers):
  w,h=(4,4) if i==0 else (r.randrange(3,6),r.randrange(3,5))
  for yy in range(max(1,y-h),min(63,y+h+1)):
   for xx in range(max(1,x-w),min(63,x+w+1)):m[yy*64+xx]=0
  if i:
   xx,yy=centers[i-1]
   while xx!=x:m[yy*64+xx]=0;xx+=1 if xx<x else -1
   while yy!=y:m[yy*64+xx]=0;yy+=1 if yy<y else -1
   m[y*64+x]=0
 # One map bank is selected per floor. The final marker becomes stairs on 1-7.
 m[55*64+55]=9;m[55*64+54]=36
 # Opening room: equipment, keeper, treasure, and one approachable slime.
 for x,y,t in [(3,4,3),(7,3,5),(3,7,6),(8,7,7),(8,5,32),(6,8,4)]:m[y*64+x]=t
 free=[i for i,t in enumerate(m) if t==0 and (i%64>11 or i//64>11) and abs(i%64-55)+abs(i//64-55)>3]
 r.shuffle(free)
 # 18 regular enemies plus the warden; only 20 slots are allocated in RAM.
 for t in [32,33,34,35]*4+[33]+[3]*12+[4]*18+[5]*7+[6]*14+[8]*8:m[free.pop()]=t
 # One rabbit Keeper per floor, at the opening room.
 return m

def audit(m):
 start=5*64+5;seen={start};q=[start]
 for p in q:
  for n in (p-1,p+1,p-64,p+64):
   if 0<=n<4096 and m[n] not in (1,7) and n not in seen:seen.add(n);q.append(n)
 assert sum(t not in (1,7) for t in m)==len(seen),'Disconnected map or keeper blocks corridor'
 assert sum(32<=t<=36 for t in m)<=20
 assert m[start]==0 and m[55*64+55]==9
 # Keep the whole boundary solid, so every one-byte coordinate remains safe.
 assert all(m[x]==m[4032+x]==m[x*64]==m[x*64+63]==1 for x in range(64))
 return len(seen)

def generate(out):
 out.mkdir(parents=True,exist_ok=True)
 gfx=make_graphics();(out/'graphics.bin').write_bytes(gfx)
 maps=[dungeon(i) for i in range(120)];counts=[audit(m) for m in maps]
 blob=b''.join(maps);(out/'dungeons.bin').write_bytes(blob)
 return {'layouts':120,'map_size':[64,64],'reachable_cells_min':min(counts),'reachable_cells_max':max(counts),'all_maps_connected':True,'all_art_original':True,'pcg_block':[2,2],'graphics_sha256':hashlib.sha256(gfx).hexdigest(),'maps_sha256':hashlib.sha256(blob).hexdigest()}
if __name__=='__main__':print(json.dumps(generate(ROOT.parent/'build'),indent=2))
